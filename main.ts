// Decode-verification guard: re-read the file just written and prove it is
// a whole PNG of the gate's shape before reporting success. Any mismatch
// fails the run instead of shipping a corrupt or mistyped artifact.
function verifyPNG(path: string): void {
  const buf = readFileSync(path);
  const sig = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
  if (!buf.subarray(0, 8).equals(sig)) throw new Error("output is not a PNG (bad signature)");
  if (buf.toString("ascii", 12, 16) !== "IHDR") throw new Error("output PNG has no IHDR first");
  const w = buf.readUInt32BE(16);
  const h = buf.readUInt32BE(20);
  if (w !== W || h !== H) throw new Error(`output PNG is ${w}x${h}, expected ${W}x${H}`);
  if (buf[24] !== 8 || buf[25] !== 6) {
    throw new Error(`unexpected PNG format: bit depth ${buf[24]}, colour type ${buf[25]}`);
  }
  let pos = 8;
  const idatParts: Buffer[] = [];
  let sawIEND = false;
  while (pos + 8 <= buf.length) {
    const len = buf.readUInt32BE(pos);
    const type = buf.toString("ascii", pos + 4, pos + 8);
    if (type === "IDAT") idatParts.push(buf.subarray(pos + 8, pos + 8 + len));
    if (type === "IEND") {
      sawIEND = true;
      break;
    }
    pos += 12 + len;
  }
  if (!sawIEND) throw new Error("output PNG has no IEND chunk");
  const raw = inflateSync(Buffer.concat(idatParts));
  if (raw.length !== H * (1 + W * 4)) {
    throw new Error(`IDAT inflates to ${raw.length} bytes, expected ${H * (1 + W * 4)}`);
  }
  for (let y = 0; y < H; y++) {
    if (raw[y * (1 + W * 4)] !== 0) throw new Error(`scanline ${y} has a non-zero filter byte`);
  }
}

function main(): void {
  const bottom = drawLetter();
  const png = encodePNG();
  if (png.length > 1048576) {
    throw new Error(`PNG too large: ${png.length} bytes (gate cap 1048576)`);
  }
  const outDir = process.env.MAKEFUN_OUTPUT_DIR || "/output";
  mkdirSync(outDir, { recursive: true });
  const dest = join(resolve(outDir), "entry.png");
  writeFileSync(dest, png);
  verifyPNG(dest);
  const sha = createHash("sha256").update(png).digest("hex");
  console.log(`letter bottom edge: y=${bottom}`);
  console.log(`wrote ${dest} (${W}x${H}, ${png.length} bytes, sha256 ${sha})`);
  console.log("verify: PNG signature, IHDR, IEND and IDAT decode all OK");
}

main();
